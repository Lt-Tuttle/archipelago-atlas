r"""The pack lab's logic batch: for every game the lab's engine loads, a YAML from the game's own options, a one-player seed
generated by the engine (a game whose output needs a ROM is generated again without that output), and the seed test
(Atlas's logic replayed over the generator's spheres: exact, late, early). Nothing connects and nothing goes online; it's
the solo test's Yaml, Generate and Score steps driven straight through the engine's components, paced one game at a time.

Usage: python Tools/batch_logic.py --corpus <folder> --lab <folder>\lab [--core <engine core>] [--only <words>] [--limit N] [--rescore]
           [--names <folder>] [--out <json>] [--part i/n] [--games <file>] [--seeds-from <json> ...] [--score-old <json> ...]
Writes <corpus>\batch\batch_logic.json (resumable: a game with a result is skipped; --rescore runs the seed test again for
every recorded game whose seed is still on disk and whose logic wasn't exact) and prints a summary at the end.
  --names       the name tables' folder whose _load_report.json lists the games (default: <corpus>\names)
  --out         the results file (default: <corpus>\batch\batch_logic.json; with --seeds-from or --score-old it must be
                given, and not be a file they read)
  --part i/n    every n-th game from the i-th only: n processes, each with a lab of its own
  --games       a file of games to run, one a line (compare_batches.py writes <report>.regressions.txt)
  --seeds-from  an earlier run's results (its parts, or a wildcard): each game generates from that run's YAML and generation
                seed (recorded as seed); a YAML that no longer generates is replaced by a fresh one (seed_reused,
                yaml_reused, reuse_error say), and kept with its seed (reused_yaml_path, reused_seed): a control run on
                these results generates that YAML and seed again when the fresh one failed too
  --score-old   score only: each earlier seed still on disk, with its YAML, on this core (a room made on another
                Archipelago, tracked on this one)
Before anything runs, the lab's copy of the bridge is written again from this tree (the lab keeps the copy it was built
with), and <out>.meta.json beside the results (batch_logic.meta.json by default) records the core's Archipelago version,
the bridge's SHA-256 and the arguments, so two batches are compared only for what they are.
"""
import argparse
import glob
import hashlib
import json
import re
import os
import shutil
import subprocess
import sys
import time
import zipfile
from datetime import datetime, timezone

sys.stdout.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.environ.get('ATLAS_PROJECT') or os.path.dirname(HERE)
PY_DIR = os.path.join(PROJECT, 'Scripts', 'Core', 'Engine', 'Python')
ROOT = os.path.dirname(PROJECT)  # the repository: Builds/ is beside AP_Atlas_Source
GENERATE_TIMEOUT = 20 * 60
OTHER_TIMEOUT = 10 * 60


def run_engine(python, core, lab, component, request, timeout):
    env = dict(os.environ)
    env.update(ATLAS_ENGINE_DATA=lab, APPDATA=os.path.join(lab, 'home', 'AppData'), LOCALAPPDATA=os.path.join(lab, 'home', 'Local'),
               TEMP=os.path.join(lab, 'home', 'Temp'), TMP=os.path.join(lab, 'home', 'Temp'), PYTHONPYCACHEPREFIX=os.path.join(lab, 'pycache'))
    for d in ('home/AppData', 'home/Local', 'home/Temp'):
        os.makedirs(os.path.join(lab, d), exist_ok=True)
    # -I ignores PYTHONPYCACHEPREFIX: the compiled files go to the lab by -X, never into the core.
    args = [python, '-I', '-X', 'pycache_prefix=' + os.path.join(lab, 'pycache'), os.path.join(PY_DIR, 'atlas_run.py'), os.path.join(core, 'archipelago'), component]
    try:
        r = subprocess.run(args, input=json.dumps(request) + '\n', capture_output=True, text=True, encoding='utf-8', errors='replace', timeout=timeout, cwd=lab, env=env)
    except subprocess.TimeoutExpired:
        return None, f'{component} took over {timeout} s'
    lines = [l for l in r.stdout.splitlines() if l.strip().startswith('{')]
    for line in reversed(lines):
        try:
            return json.loads(line), r.stderr[-2000:]
        except json.JSONDecodeError:
            continue
    return None, (r.stderr or r.stdout)[-2000:]


def safe(name):
    return ''.join('_' if c in '<>:"/\\|?*' else c for c in name)


def core_version(core):
    """The core's Archipelago version, from its Utils.py; None without one."""
    try:
        with open(os.path.join(core, 'archipelago', 'Utils.py'), encoding='utf-8-sig') as f:
            found = re.search(r'__version__\s*=\s*["\']([^"\']+)["\']', f.read())
    except OSError:
        return None
    return found.group(1) if found else None


def refresh_bridge(lab):
    """The lab's UltimateBridge.apworld (the bridge its engine loads) written again from this tree's atlas_bridge.py when it
    differs; the bridge's SHA-256."""
    with open(os.path.join(PY_DIR, 'atlas_bridge.py'), 'rb') as f:
        source = f.read()
    worlds = os.path.join(lab, 'ap', 'worlds')
    path = os.path.join(worlds, 'UltimateBridge.apworld')
    try:
        with zipfile.ZipFile(path) as z:
            current = z.read('UltimateBridge/__init__.py')
    except (OSError, KeyError, zipfile.BadZipFile):
        current = None
    if current != source:
        os.makedirs(worlds, exist_ok=True)
        with zipfile.ZipFile(path + '.part', 'w') as z:
            z.writestr('UltimateBridge/__init__.py', source)
        os.replace(path + '.part', path)
        print("wrote the lab's bridge from",os.path.join(PY_DIR, 'atlas_bridge.py'), flush=True)
    return hashlib.sha256(source).hexdigest()


def batch_files(paths):
    """The results files named, a wildcard expanded here (Windows shells pass it as typed); a run's .meta.json isn't results."""
    files = []
    for path in paths:
        for found in sorted(glob.glob(path)) if any(c in path for c in '*?[') else [path]:
            if not found.lower().endswith('.meta.json') and found not in files:
                files.append(found)
    return files


def read_batches(paths):
    """Results of earlier runs, a run's parts merged."""
    results = {}
    for found in batch_files(paths):
        with open(found, encoding='utf-8-sig') as f:
            for game, entry in json.load(f).items():
                if game not in results or entry.get('finished'):
                    results[game] = entry
    return results


def spoiler_seed(multidata):
    """The generation's own seed, from the spoiler's first line beside the seed's data (the seed's name is drawn from it,
    not the same); None without a spoiler."""
    folder = os.path.dirname(multidata or '')
    if not multidata or not os.path.isdir(folder):
        return None
    spoilers = [f for f in os.listdir(folder) if f.endswith('_Spoiler.txt')]
    if not spoilers:
        return None
    with open(os.path.join(folder, spoilers[0]), encoding='utf-8-sig') as f:
        found = re.search(r'Seed:\s*(\d+)', f.readline())
    return found.group(1) if found else None


def old_seed(entry):
    """What an earlier run's game lends this one: its YAML's file name and bytes, and its generation seed; read before the
    game's folder is cleared (that run may have used this lab). A game whose lent YAML failed to generate there, and the
    fresh one after it (no seed came of either), lends the YAML and seed that failed: a control run generates the same
    input on the old core. None without the YAML on disk."""
    entry = entry or {}
    kept = entry.get('reused_yaml_path')
    if kept and not entry.get('multidata') and os.path.isfile(kept):
        yaml_path, seed = kept, entry.get('reused_seed')
    else:
        yaml_path, seed = entry.get('yaml_path'), spoiler_seed(entry.get('multidata')) or entry.get('seed')
    if not yaml_path or not os.path.isfile(yaml_path):
        return None
    with open(yaml_path, 'rb') as f:
        data = f.read()
    return os.path.basename(yaml_path), data, seed


def set_aside(entry, folder, reuse, error):
    """An earlier run's YAML that doesn't generate on this core, kept with its seed beside the game's players folder (the
    fresh YAML's), for old_seed."""
    name, data, seed = reuse
    kept = os.path.join(folder, 'reused', name)
    os.makedirs(os.path.dirname(kept), exist_ok=True)
    with open(kept, 'wb') as f:
        f.write(data)
    entry.update(yaml_reused=False, seed_reused=False, reuse_error=error, reused_yaml_path=kept, reused_seed=seed, seed=None)


def fresh_folder(folder):
    if os.path.isdir(folder):
        shutil.rmtree(folder, ignore_errors=True)
    players, output = os.path.join(folder, 'players'), os.path.join(folder, 'output')
    os.makedirs(players, exist_ok=True)
    os.makedirs(output, exist_ok=True)
    return players, output


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--corpus', required=True)
    ap.add_argument('--lab', required=True)
    ap.add_argument('--core', default=os.path.join(ROOT, 'Builds', 'engine-core'))
    ap.add_argument('--only', default='')
    ap.add_argument('--limit', type=int, default=0)
    ap.add_argument('--start-at', default='', help='skip the games sorted before this one (to resume an interrupted --rescore or --replay)')
    ap.add_argument('--rescore', action='store_true')
    ap.add_argument('--replay', action='store_true', help="replay each differing seed against the generator's own world (AtlasSeedReplay)")
    ap.add_argument('--compare', action='store_true', help="with --replay: compare the generator's world with the one Atlas rebuilds (options, values, entrances)")
    ap.add_argument('--names', default='', help="the name tables' folder whose _load_report.json lists the games (default: <corpus>\\names)")
    ap.add_argument('--out', default='', help='the results file (default: <corpus>\\batch\\batch_logic.json)')
    ap.add_argument('--part', default='', help='i/n: every n-th game from the i-th only (n processes, a lab each)')
    ap.add_argument('--games', default='', help='a file of games to run, one a line')
    ap.add_argument('--seeds-from', nargs='+', default=[], help="an earlier run's results: each game reuses its YAML and generation seed")
    ap.add_argument('--score-old', nargs='+', default=[], help="score only: each earlier run's seed still on disk, with its YAML, on this core")
    args = ap.parse_args()
    part = re.fullmatch(r'(\d+)/(\d+)', args.part) if args.part else None
    if args.part and not (part and 1 <= int(part.group(1)) <= int(part.group(2))):
        ap.error('--part takes i/n, with 1 <= i <= n')
    if args.score_old and (args.seeds_from or args.rescore or args.replay):
        ap.error('--score-old only scores: not with --seeds-from, --rescore or --replay')
    # A run on an earlier run's seeds writes a file of its own: never the default (the batch it compares with, most often).
    if (args.seeds_from or args.score_old) and not args.out:
        ap.error('--seeds-from and --score-old need --out (a results file of their own)')
    if args.out and os.path.abspath(args.out) in {os.path.abspath(p) for p in batch_files(args.seeds_from + args.score_old)}:
        ap.error(f'--out is a file this run reads (--seeds-from or --score-old): {args.out}')
    lab = os.path.abspath(args.lab)
    python = os.path.join(args.core, 'python', 'python.exe')
    old_runs = read_batches(args.score_old) if args.score_old else None
    if old_runs is not None:
        games = sorted(g for g, e in old_runs.items() if e.get('multidata') and os.path.isfile(e['multidata']))
    else:
        report = json.load(open(os.path.join(args.names or os.path.join(args.corpus, 'names'), '_load_report.json'), encoding='utf-8-sig'))
        games = sorted(g for g in report.get('games', {}) if g not in ('Archipelago', 'Universal Tracker'))
    if args.games:
        with open(args.games, encoding='utf-8-sig') as f:
            wanted = {line.strip() for line in f if line.strip()}
        for game in sorted(wanted - set(games)):
            print("  not in this run's games:", game, flush=True)
        games = [g for g in games if g in wanted]
    games = [g for g in games if args.only.lower() in g.lower()]
    if part:
        # The same slice on every rerun (before --start-at), so an interrupted part resumes with its own games.
        games = games[int(part.group(1)) - 1::int(part.group(2))]
    games = [g for g in games if g.lower() >= args.start_at.lower()]
    out_path = os.path.abspath(args.out) if args.out else os.path.join(args.corpus, 'batch', 'batch_logic.json')
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    results = json.load(open(out_path, encoding='utf-8-sig')) if os.path.exists(out_path) else {}
    seeds = read_batches(args.seeds_from) if args.seeds_from else None

    # What runs, beside the results: the core's Archipelago and the bridge the lab's engine loads (written from this tree
    # first). Each run of the same file is added, so a resume on another core or bridge shows.
    run = {'archipelago': core_version(args.core), 'bridge_sha256': refresh_bridge(lab), 'core': os.path.abspath(args.core), 'lab': lab,
           'arguments': sys.argv[1:], 'started': datetime.now(timezone.utc).isoformat()}
    meta_path = os.path.splitext(out_path)[0] + '.meta.json'
    runs = (json.load(open(meta_path, encoding='utf-8-sig')).get('runs') or []) if os.path.exists(meta_path) else []
    if results and any((r.get('archipelago'), r.get('bridge_sha256')) != (run['archipelago'], run['bridge_sha256']) for r in runs):
        print(f'note: {out_path} also holds results from another core or bridge ({meta_path})', flush=True)
    with open(meta_path, 'w', encoding='utf-8') as f:
        json.dump(dict(run, runs=runs + [run]), f, indent=1, ensure_ascii=False)

    def save():
        with open(out_path, 'w', encoding='utf-8') as f:
            json.dump(results, f, indent=1, ensure_ascii=False)

    def score(game, entry, started):
        yaml_paths = {'1': entry['yaml_path']} if entry.get('yaml_path') else {}
        answer, err = run_engine(python, args.core, lab, 'AtlasSeedTest', {'seed': entry.get('multidata'), 'yaml_paths': yaml_paths, 'check': True}, OTHER_TIMEOUT)
        if not answer or not answer.get('players'):
            entry.update(step='score', error=(answer or {}).get('error') or err, finished=True)
            print('   score failed:', str(entry['error'])[:160], flush=True)
            save()
            return False
        p = answer['players'][0]
        steps = p.get('steps') or []
        entry.update(step='done', exact=p.get('exact'), checksum_match=p.get('checksum_match'), late=sum(s.get('late_count', 0) for s in steps),
                     early=sum(s.get('early_count', 0) for s in steps), score_error=p.get('error'), score_seconds=p.get('seconds'),
                     late_examples=[x for s in steps for x in s.get('late', [])][:8], early_examples=[x for s in steps for x in s.get('early', [])][:8],
                     seconds=round(time.time() - started, 1), finished=True)
        # For judging a difference: how the slot's world was rebuilt (and whether it matched the seed's), and where it first differs.
        # With the second rebuild: exact once the locations Atlas calls unsure are set apart; exact_all without that.
        entry.update(unsure=p.get('unsure'), exact_all=p.get('exact_all'), check=p.get('check'), rebuilds=p.get('rebuilds'), differs=p.get('differs'))
        entry.update(rebuild=p.get('rebuild'), first_difference=next((s for s in steps if s.get('late_count') or s.get('early_count')), None),
                     sphere_counts=[[s.get('expected'), s.get('reachable'), s.get('late_count'), s.get('early_count')] for s in steps])
        print(f"   {'exact' if entry['exact'] else 'differs'}: {entry['locations']} locations, {entry['spheres']} spheres, late {entry['late']}, early {entry['early']}, unsure {entry.get('unsure')} ({entry['seconds']} s)", flush=True)
        save()
        return True

    if args.replay:
        # Each seed whose logic differed, generated again and replayed against the generator's own world: exact there means
        # the world Atlas rebuilds isn't the seed's; differing there too means the test's reading of the spheres.
        for game in games:
            entry = results.get(game)
            if not entry or entry.get('step') != 'done' or entry.get('exact') or not entry.get('multidata') or not os.path.exists(entry['multidata']):
                continue
            players = os.path.join(lab, 'batch', safe(game), 'players')
            seed = spoiler_seed(entry['multidata'])
            print(f'[replay] {game}', flush=True)
            answer, err = run_engine(python, args.core, lab, 'AtlasSeedReplay',
                                     {'multidata': entry['multidata'], 'players_dir': players, 'seed': seed, 'player': 1, 'skip_patch_games': [game],
                                      'compare': args.compare, 'yaml_path': entry.get('yaml_path')}, OTHER_TIMEOUT)
            if not answer or answer.get('error'):
                entry['replay'] = {'error': (answer or {}).get('error') or err}
                print('   replay failed:', str(entry['replay']['error'])[-200:], flush=True)
            else:
                entry['replay'] = {k: answer.get(k) for k in ('exact', 'late', 'early', 'same_seed', 'accessibility', 'seconds')}
                entry['replay']['first_difference'] = next((s for s in answer.get('steps') or [] if s.get('late_count') or s.get('early_count')), None)
                if answer.get('compare') is not None:
                    entry['compare'] = answer['compare']
                    c = answer['compare']
                    print(f"   compare: options {c.get('options_count')}, values {c.get('values_count')}, entrances {c.get('entrances_count')}, locked {c.get('locked_count')}{' ' + str(c.get('error'))[-150:] if c.get('error') else ''}", flush=True)
                print(f"   replay {'exact' if answer.get('exact') else 'differs'}: late {answer.get('late')}, early {answer.get('early')}, same seed {answer.get('same_seed')}", flush=True)
            save()
        games = []

    if args.rescore:
        # The seed test again, with the YAML, for every recorded seed still on disk whose logic wasn't exact.
        for game in games:
            entry = results.get(game)
            if not entry or entry.get('step') != 'done' or entry.get('exact') or not entry.get('multidata') or not os.path.exists(entry['multidata']):
                continue
            if not entry.get('yaml_path'):
                players = os.path.join(lab, 'batch', safe(game), 'players')
                yamls = sorted(f for f in os.listdir(players) if f.lower().endswith(('.yaml', '.yml'))) if os.path.isdir(players) else []
                if yamls:
                    entry['yaml_path'] = os.path.join(players, yamls[0])
            print(f'[rescore] {game}', flush=True)
            score(game, entry, time.time())
        games = []

    done = 0
    if old_runs is not None:
        # Each earlier seed scored again on this core with its own YAML: a room made on the old Archipelago, tracked on
        # this one (checksum_match says whether the world is still the one the seed was made with).
        for game in games:
            if game in results and results[game].get('finished'):
                continue
            if args.limit and done >= args.limit:
                break
            done += 1
            old = old_runs[game]
            entry = {'started': datetime.now(timezone.utc).isoformat(), 'score_old': True}
            entry.update({k: old.get(k) for k in ('seed_name', 'locations', 'items', 'spheres', 'sphere0', 'multidata')})
            entry['yaml_path'] = old['yaml_path'] if old.get('yaml_path') and os.path.isfile(old['yaml_path']) else None
            results[game] = entry
            print(f'[{done}] {game}', flush=True)
            score(game, entry, time.time())
        games = []

    def make_yaml(game, entry, players):
        answer, err = run_engine(python, args.core, lab, 'AtlasYamlTemplate', {'game': game, 'player_name': 'AtlasTest', 'output_dir': players}, OTHER_TIMEOUT)
        if not answer or not answer.get('ok'):
            entry.update(step='yaml', error=(answer or {}).get('error') or err, trace=(answer or {}).get('trace'), finished=True)
            print('   yaml failed:', str(entry['error'])[:160], flush=True)
            save()
            return False
        entry['yaml_from'] = answer.get('from')
        entry['yaml_path'] = answer.get('path')
        options = answer.get('options')
        entry['options'] = options if isinstance(options, int) else len(options or [])
        return True

    def generate(game, entry, players, output, seed):
        # The answer, or None with what failed (both tries: as is, then without the output a ROM would need).
        request = {'players_dir': players, 'output_dir': output, 'spoiler': 3, 'skip_patch_games': []}
        if seed is not None:
            request['seed'] = seed
        answer, err = run_engine(python, args.core, lab, 'AtlasGenerate', request, GENERATE_TIMEOUT)
        if not answer or not answer.get('ok'):
            first, first_trace = (answer or {}).get('error') or err, (answer or {}).get('trace')
            request['skip_patch_games'] = [game]
            answer, err = run_engine(python, args.core, lab, 'AtlasGenerate', request, GENERATE_TIMEOUT)
            entry['patch_skipped'] = True
            if not answer or not answer.get('ok'):
                return None, {'error': (answer or {}).get('error') or err, 'trace': (answer or {}).get('trace'), 'first_error': first, 'first_trace': first_trace}
        return answer, None

    for game in games:
        if game in results and results[game].get('finished'):
            continue
        if args.limit and done >= args.limit:
            break
        done += 1
        started = time.time()
        entry = {'started': datetime.now(timezone.utc).isoformat()}
        results[game] = entry
        folder = os.path.join(lab, 'batch', safe(game))
        reuse = old_seed(seeds.get(game)) if seeds is not None else None
        players, output = fresh_folder(folder)
        print(f'[{done}] {game}', flush=True)
        seed = None
        if seeds is not None:
            entry.update(yaml_reused=reuse is not None, seed_reused=bool(reuse and reuse[2] is not None),
                         reuse_error=None if reuse else "the earlier run's YAML isn't on disk")
        if reuse:
            name, data, seed = reuse
            entry['yaml_path'] = os.path.join(players, name)
            with open(entry['yaml_path'], 'wb') as f:
                f.write(data)
            entry.update(yaml_from=seeds[game].get('yaml_from'), options=seeds[game].get('options'), seed=seed)
        elif not make_yaml(game, entry, players):
            continue
        answer, failure = generate(game, entry, players, output, seed)
        if failure and reuse:
            # The earlier run's YAML doesn't generate on this core: a fresh one from the game's options, said in the entry.
            print('   the earlier YAML failed:', str(failure['error'])[:160], flush=True)
            entry.pop('patch_skipped', None)
            players, output = fresh_folder(folder)
            set_aside(entry, folder, reuse, failure['error'])
            if not make_yaml(game, entry, players):
                continue
            answer, failure = generate(game, entry, players, output, None)
        if failure:
            entry.update(step='generate', finished=True, **failure)
            print('   generate failed:', str(entry['error'])[:160], flush=True)
            save()
            continue
        player = ((answer.get('players') or [{}])[0]) or {}
        entry.update(seed_name=answer.get('seed_name'), locations=player.get('locations'), items=player.get('items'), spheres=answer.get('spheres'),
                     sphere0=answer.get('sphere0'), generate_seconds=answer.get('seconds'), multidata=answer.get('multidata'))
        if not score(game, entry, started):
            continue
        # Every seed's folder is kept (about 100 KB a game): the spoiler helps a look at a difference, and the YAML probe
        # (whether the logic rebuilds without the player's YAML) scores the same seed again.

    finished = [g for g, r in results.items() if r.get('finished')]
    exact = [g for g in finished if results[g].get('exact')]
    differs = [g for g in finished if results[g].get('step') == 'done' and not results[g].get('exact')]
    failed = [g for g in finished if results[g].get('step') != 'done']
    print(f'\n{len(finished)} games: {len(exact)} exact, {len(differs)} differ, {len(failed)} failed to generate or score')
    for g in differs[:40]:
        print(f'  differs: {g}: late {results[g]["late"]}, early {results[g]["early"]}; {results[g]["late_examples"][:3]} / {results[g]["early_examples"][:3]}')
    for g in failed[:60]:
        print(f'  failed ({results[g].get("step")}): {g}: {str(results[g].get("error"))[:140]}')


if __name__ == '__main__':
    main()
